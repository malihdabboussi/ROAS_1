  ON agent_employee_templates(is_enabled, sort_order, created_at);

ALTER TABLE agent_employee_templates ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS agent_employee_templates_read_all ON agent_employee_templates;
