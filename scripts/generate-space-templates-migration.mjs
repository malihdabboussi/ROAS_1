/**
 * Generates supabase/migrations/20260520120100_seed_space_templates.sql from catalog TS.
 * Run: node scripts/generate-space-templates-migration.mjs
 */
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const { execSync } = await import('node:child_process')
const root = join(dirname(fileURLToPath(import.meta.url)), '..')

const catalogJson = execSync(
  `npx --yes tsx -e "import { SPACE_TEMPLATE_CATALOG } from './apps/api/src/modules/space-templates/data/space-template-catalog.ts'; console.log(JSON.stringify(SPACE_TEMPLATE_CATALOG))"`,
  { cwd: root, encoding: 'utf8' },
)

const catalog = JSON.parse(catalogJson.trim())

function sqlString(value) {
  if (value == null) return 'NULL'
  return `'${String(value).replace(/'/g, "''")}'`
}

function sqlJson(value) {
  return `${sqlString(JSON.stringify(value))}::jsonb`
}

function inlineMarkdown(value) {
  return value.replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>')
}

function markdownToHtml(value) {
  if (value == null) return null
  if (/<[a-z][\s\S]*>/i.test(value)) return value
  const lines = String(value).split('\n')
  const out = []
  let list = []
  const flushList = () => {
    if (list.length === 0) return
    out.push(`<ul>${list.map((line) => `<li>${inlineMarkdown(line)}</li>`).join('')}</ul>`)
    list = []
  }
  for (const rawLine of lines) {
    const line = rawLine.trim()
    if (!line) {
      flushList()
      continue
    }
    if (line.startsWith('# ')) {
      flushList()
      out.push(`<h1>${inlineMarkdown(line.slice(2))}</h1>`)
      continue
    }
    if (line.startsWith('## ')) {
      flushList()
      out.push(`<h2>${inlineMarkdown(line.slice(3))}</h2>`)
      continue
    }
    if (line.startsWith('- ')) {
      list.push(line.slice(2))
      continue
    }
    flushList()
    out.push(`<p>${inlineMarkdown(line)}</p>`)
  }
  flushList()
  return out.join('\n')
}

const templateInserts = []
const itemInserts = []
const automationInserts = []

for (const tpl of catalog) {
  const tplVar = `tpl_${tpl.slug.replace(/-/g, '_')}`
  templateInserts.push(`  (
    gen_random_uuid(),
    ${sqlString(tpl.slug)},
    ${sqlString(tpl.title)},
    ${sqlString(tpl.description)},
    ${sqlString(tpl.icon)},
    ${sqlString(tpl.icon_color)},
    ${sqlString(tpl.category)},
    ${tpl.persona ? sqlString(tpl.persona) : 'NULL'},
    ${tpl.badge ? sqlString(tpl.badge) : 'NULL'},
    ${tpl.featured ? 'true' : 'false'},
    ${tpl.is_new ? 'true' : 'false'},
    ${sqlJson(tpl.schema)},
    ${tpl.channel_name ? sqlString(tpl.channel_name) : 'NULL'},
    ${tpl.channel_description ? sqlString(tpl.channel_description) : 'NULL'},
    ${tpl.sort_order}
  )`)

  for (const item of tpl.items) {
    itemInserts.push({
      slug: tpl.slug,
      kind: item.kind,
      title: item.title,
      status: item.status ?? null,
      priority: item.priority ?? 'medium',
      description: item.description ?? null,
      body: markdownToHtml(item.body ?? null),
      custom_data: item.custom_data ?? {},
      sort_order: item.sort_order,
    })
  }

  for (const auto of tpl.automations) {
    automationInserts.push({
      slug: tpl.slug,
      name: auto.name,
      trigger: auto.trigger,
      actions: auto.actions,
      sort_order: auto.sort_order,
    })
  }
}

const templateValues = templateInserts.join(',\n')

const itemRows = itemInserts
  .map(
    (item) => `  (
    (SELECT id FROM public.space_templates WHERE slug = ${sqlString(item.slug)}),
    ${sqlString(item.kind)},
    ${sqlString(item.title)},
    ${item.status ? sqlString(item.status) : 'NULL'},
    ${sqlString(item.priority)},
    ${item.description ? sqlString(item.description) : 'NULL'},
    ${item.body ? sqlString(item.body) : 'NULL'},
    ${sqlJson(item.custom_data)},
    ${item.sort_order}
  )`,
  )
  .join(',\n')

const automationRows = automationInserts
  .map(
    (auto) => `  (
    (SELECT id FROM public.space_templates WHERE slug = ${sqlString(auto.slug)}),
    ${sqlString(auto.name)},
    ${sqlJson(auto.trigger)},
    ${sqlJson(auto.actions)},
    ${auto.sort_order}
  )`,
  )
  .join(',\n')

const sql = `-- Generated by scripts/generate-space-templates-migration.mjs — do not hand-edit rows.
BEGIN;

INSERT INTO public.space_templates (
  id,
  slug,
  title,
  description,
  icon,
  icon_color,
  category,
  persona,
  badge,
  featured,
  is_new,
  schema,
  channel_name,
  channel_description,
  sort_order
)
VALUES
${templateValues}
ON CONFLICT (slug) DO UPDATE SET
  title = EXCLUDED.title,
  description = EXCLUDED.description,
  icon = EXCLUDED.icon,
  icon_color = EXCLUDED.icon_color,
  category = EXCLUDED.category,
  persona = EXCLUDED.persona,
  badge = EXCLUDED.badge,
  featured = EXCLUDED.featured,
  is_new = EXCLUDED.is_new,
  schema = EXCLUDED.schema,
  channel_name = EXCLUDED.channel_name,
  channel_description = EXCLUDED.channel_description,
  sort_order = EXCLUDED.sort_order,
  updated_at = now();

DELETE FROM public.space_template_items
WHERE template_id IN (SELECT id FROM public.space_templates WHERE slug IN (${catalog.map((t) => sqlString(t.slug)).join(', ')}));

DELETE FROM public.space_template_automations
WHERE template_id IN (SELECT id FROM public.space_templates WHERE slug IN (${catalog.map((t) => sqlString(t.slug)).join(', ')}));

INSERT INTO public.space_template_items (
  template_id,
  kind,
  title,
  status,
  priority,
  description,
  body,
  custom_data,
  sort_order
)
VALUES
${itemRows};

${automationInserts.length > 0 ? `INSERT INTO public.space_template_automations (
  template_id,
  name,
  trigger,
  actions,
  sort_order
)
VALUES
${automationRows};` : '-- No template automations'}

COMMIT;
`

const outPath = join(root, 'supabase/migrations/20260520120100_seed_space_templates.sql')
writeFileSync(outPath, sql, 'utf8')
console.log(`Wrote ${outPath} (${catalog.length} templates, ${itemInserts.length} items, ${automationInserts.length} automations)`)
