/**
 * Generates supabase/migrations/*_seed_space_automation_templates.sql from catalog TS.
 * Run: node scripts/generate-space-automation-templates-migration.mjs
 */
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createRequire } from 'node:module'

const require = createRequire(import.meta.url)
const root = join(dirname(fileURLToPath(import.meta.url)), '..')

// Register ts-node style: use jiti or compile - simplest: dynamic import via tsx
// Fallback: read catalog by spawning tsx
const { execSync } = await import('node:child_process')
const catalogJson = execSync(
  `npx --yes tsx -e "import { SPACE_AUTOMATION_TEMPLATE_CATALOG } from './apps/api/src/modules/spaces/data/space-automation-template-catalog.ts'; console.log(JSON.stringify(SPACE_AUTOMATION_TEMPLATE_CATALOG))"`,
  { cwd: root, encoding: 'utf8' },
)

const catalog = JSON.parse(catalogJson.trim())

function sqlString(value) {
  return `'${String(value).replace(/'/g, "''")}'`
}

function sqlArray(values) {
  if (!values?.length) return 'ARRAY[]::text[]'
  return `ARRAY[${values.map((v) => sqlString(v)).join(', ')}]::text[]`
}

const rows = catalog
  .map((row) => {
    const body = sqlString(JSON.stringify(row.body))
    return `  (
    ${sqlString(row.template_key)},
    ${sqlString(row.title)},
    ${sqlString(row.description)},
    ${sqlString(row.badge)},
    ${row.featured ? 'true' : 'false'},
    ${row.is_new ? 'true' : 'false'},
    ${sqlArray(row.workflows)},
    ${row.integration ? sqlString(row.integration) : 'NULL'},
    ${row.trigger_group ? sqlString(row.trigger_group) : 'NULL'},
    ${body}::jsonb,
    ${row.sort_order}
  )`
  })
  .join(',\n')

const sql = `-- Generated by scripts/generate-space-automation-templates-migration.mjs — do not hand-edit rows.
BEGIN;

INSERT INTO public.space_automation_templates (
  template_key,
  title,
  description,
  badge,
  featured,
  is_new,
  workflows,
  integration,
  trigger_group,
  body,
  sort_order
)
VALUES
${rows}
ON CONFLICT (template_key) DO UPDATE SET
  title = EXCLUDED.title,
  description = EXCLUDED.description,
  badge = EXCLUDED.badge,
  featured = EXCLUDED.featured,
  is_new = EXCLUDED.is_new,
  workflows = EXCLUDED.workflows,
  integration = EXCLUDED.integration,
  trigger_group = EXCLUDED.trigger_group,
  body = EXCLUDED.body,
  sort_order = EXCLUDED.sort_order,
  version = public.space_automation_templates.version + 1,
  updated_at = now();

COMMIT;
`

const outPath = join(
  root,
  'supabase/migrations/20260521120000_space_automation_templates.sql',
)
writeFileSync(outPath, sql, 'utf8')
console.log(`Wrote ${outPath} (${catalog.length} templates)`)
